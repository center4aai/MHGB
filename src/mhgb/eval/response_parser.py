"""
Парсер структурированных ответов тестируемых моделей.

Тестируемые модели обязаны отвечать в формате EXPECTED_ANSWER_FORMAT:
  ПРИМЕНИМЫЕ СТАТЬИ: ...
  ЦЕПОЧКА РАССУЖДЕНИЙ: ...
  ВЫВОД: ...

Этот модуль извлекает три секции для последующего вычисления метрик:
  - Norm Coverage по явному списку статей
  - Norm Coverage по упоминаниям в тексте рассуждения
  - Answer Correctness по выводу
"""

from __future__ import annotations

import re
from typing import TypedDict


class StructuredAnswer(TypedDict):
    """Три секции структурированного ответа модели."""

    applicable_articles: str  # содержимое секции ПРИМЕНИМЫЕ СТАТЬИ
    reasoning: str            # содержимое секции ЦЕПОЧКА РАССУЖДЕНИЙ
    conclusion: str           # содержимое секции ВЫВОД


# Паттерны заголовков секций (регистронезависимые)
_SECTION_PATTERNS: list[tuple[re.Pattern[str], str]] = [
    (re.compile(r"ПРИМЕНИМЫЕ\s+СТАТЬИ\s*:", re.IGNORECASE), "applicable_articles"),
    (re.compile(r"ЦЕПОЧКА\s+РАССУЖДЕНИЙ\s*:",  re.IGNORECASE), "reasoning"),
    (re.compile(r"ВЫВОД\s*:",                    re.IGNORECASE), "conclusion"),
]


# ---------------------------------------------------------------------------
# Извлечение упоминаний норм из произвольного текста
# ---------------------------------------------------------------------------

# Номер статьи: целое или дробное (12.1)
_ART_NUM_RE = r"\d+(?:\.\d+)?"
# Разделители в списках: «ст. 81 и 82», «ст. 81, 82»
_ART_SEP_RE = r"(?:\s*[,–\-]\s*|\s+и\s+)"
_ART_RANGE_RE = rf"{_ART_NUM_RE}(?:{_ART_SEP_RE}{_ART_NUM_RE})*"

# Полные и короткие формы названий законов
_LAW_PAT = (
    r"(?:"
    r"[Кк]одекса?\s+об\s+административных\s+правонарушениях(?:\s+(?:РФ|Российской\s+Федерации))?"
    r"|(?:Трудового|Гражданского|Семейного|Жилищного|Уголовного|Налогового|Земельного|Градостроительного)"
    r"\s+[Кк]одекса?(?:\s+(?:РФ|Российской\s+Федерации))?"
    r"|[Кк]онституции?(?:\s+(?:РФ|Российской\s+Федерации))?"
    r"|КоАП(?:\s+РФ)?"
    r"|(?:ТК|ГК|СК|ЖК|УК|НК|ЗК|ГрК)(?:\s+РФ)?"
    r")"
)

# Триггер: «ст.», «ст », «статьей», «статьями» и т.д.
_ST_PAT = r"(?:ст\.?\s*|стат(?:ей|ьями?|ьях|ьей|ьи|ье|ью|ья)\s+)"

# Основной паттерн: «ст. 261 ТК РФ» или «статьёй 261 Трудового кодекса»
# Группа 1 — номера статей, группа 2 — название закона
NORM_PATTERN = re.compile(
    rf"{_ST_PAT}({_ART_RANGE_RE})\s*({_LAW_PAT})",
    re.IGNORECASE,
)

# Приоритетные проверки для нормализации названия закона → короткий код.
# Длинные формы — раньше, чтобы короткие не перехватили.
_LAW_CHECKS: list[tuple[str, str]] = [
    (r"административных\s+правонарушениях|коап", "КоАП"),
    (r"трудового\s+кодекс",          "ТК"),
    (r"гражданского\s+кодекс",       "ГК"),
    (r"семейного\s+кодекс",          "СК"),
    (r"жилищного\s+кодекс",          "ЖК"),
    (r"уголовного\s+кодекс",         "УК"),
    (r"налогового\s+кодекс",         "НК"),
    (r"земельного\s+кодекс",         "ЗК"),
    (r"градостроительного\s+кодекс|грк", "ГрК"),
    (r"конституци",                  "КРФ"),
    # Короткие формы — в последнюю очередь
    (r"тк",  "ТК"),
    (r"гк",  "ГК"),
    (r"ск",  "СК"),
    (r"жк",  "ЖК"),
    (r"ук",  "УК"),
    (r"нк",  "НК"),
    (r"зк",  "ЗК"),
]


def _normalize_law(law_str: str) -> str | None:
    """«Трудового кодекса РФ» → «ТК», «ТК РФ» → «ТК», None если не распознано."""
    sl = law_str.strip().lower()
    for pattern, code in _LAW_CHECKS:
        if re.search(pattern, sl):
            return code
    return None


def extract_norms_from_text(text: str, corpus: dict) -> set[str]:
    """
    Извлекает упоминания правовых норм из произвольного текста и нормализует
    к формату «ТК_261» (как в corpus и графе).

    Поддерживает:
    - «ст. 261 ТК РФ», «ст.261 ТК», «статьёй 261 Трудового кодекса»
    - Списки: «ст. 81 и 82 ГК РФ», «ст. 81, 82 ГК РФ»
    - Дробные номера: «ст. 12.1 КоАП РФ»
    - Регистровые вариации: «Ст.261 ТК», «СТ. 261 ТК»

    Возвращает только нормы, присутствующие в corpus (фильтрует галлюцинации).
    """
    # ё и е взаимозаменяемы в российских НПА и ответах LLM
    normalized = text.replace("ё", "е").replace("Ё", "Е")

    found: set[str] = set()
    for m in NORM_PATTERN.finditer(normalized):
        nums_raw = m.group(1)
        law_str  = m.group(2)
        code = _normalize_law(law_str)
        if code is None:
            continue
        # Токены статей: X.Y-N (суффикс), N-M (диапазон), X.Y, N.
        # Дефис-суффикс «25.13-1» = ЕДИНАЯ статья; corpus сворачивает её в
        # базовую «НК_25.13» (D5.1), поэтому маппим X.Y-N → базовую X.Y (иначе
        # findall дробит «25.13-1» на 25.13 + 1 → фантомная норма №1).
        # Диапазон целых «254-269» / дробных «346.37-346.38» → оба конца (как раньше).
        for tok in re.findall(r"\d+(?:\.\d+)?(?:-\d+(?:\.\d+)?)?", nums_raw):
            if "-" in tok:
                left, right = tok.split("-", 1)
                if "." in left and "." not in right:
                    nums = [left]            # X.Y-N суффикс → базовая X.Y
                else:
                    nums = [left, right]     # диапазон → концы
            else:
                nums = [tok]
            for num in nums:
                norm_id = f"{code}_{num}"
                if norm_id in corpus:
                    found.add(norm_id)

    return found


def parse_structured_answer(text: str) -> StructuredAnswer:
    """
    Извлекает три секции из структурированного ответа модели.

    Порядок секций в тексте не фиксирован — функция находит каждый заголовок
    по позиции и берёт содержимое до следующего заголовка.

    Пропущенные секции возвращаются как пустые строки.
    """
    result: StructuredAnswer = {
        "applicable_articles": "",
        "reasoning": "",
        "conclusion": "",
    }

    found: list[tuple[int, int, str]] = []
    for pattern, key in _SECTION_PATTERNS:
        m = pattern.search(text)
        if m:
            found.append((m.start(), m.end(), key))

    found.sort(key=lambda x: x[0])

    for i, (_, header_end, key) in enumerate(found):
        next_start = found[i + 1][0] if i + 1 < len(found) else len(text)
        result[key] = text[header_end:next_start].strip()

    return result
